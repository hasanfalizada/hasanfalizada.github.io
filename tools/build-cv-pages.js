#!/usr/bin/env node
// +++===+++ 2026-11-05 Asia/Baku — Hasan Alizada — CV variant pages builder (no npm, no external services).
//
// For every key of cv_profiles in data/resume.json (except "default", which is the site's "Resume" button) this script
// generates cv/<profile>/index.html — an unlisted page that downloads the CV variant as PDF:
//     https://hasanalizada.net/cv/solution-architect/
// The pages hold NO resume content: PDFGenerator renders it in the browser from data/resume.json (single source of truth).
// Pages are noindex and are not added to sitemap.xml. Unlisted is not private: resume.json itself is public.
// Pages of profiles removed from resume.json are deleted. Version (?v=) is read from index.html.
// +++===+++ 2026-11-09 Asia/Baku — Hasan Alizada — cv/index.html: private page with a download button and a copy-link button per role,
// behind a primitive passcode (tools/set-cv-passcode.js). A convenience, not security: the code and the CV pages are public.
//
// Usage (from the repository root, after changing cv_profiles):
//     node tools/build-cv-pages.js

'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const rel = (...p) => path.join(ROOT, ...p);
const log = (...a) => console.log('[build-cv-pages]', ...a);

const ResumeDataLoader = require(rel('atoms/resume-data-loader/impl.js'));
const {SALT} = require('./lib/cv-passcode.js');
console.debug = () => {}; // silence atoms' debug logging in CLI output

const raw = JSON.parse(fs.readFileSync(rel('data/resume.json'), 'utf8'));
const loader = new ResumeDataLoader();
const validation = loader.validateResumeStructure(raw);
if (!validation.valid) throw new Error('resume.json is invalid: ' + validation.errors.join('; '));

const indexHtml = fs.readFileSync(rel('index.html'), 'utf8');
const vMatch = indexHtml.match(/assets\/js\/main\.js\?v=([^"']+)/);
const v = vMatch ? `?v=${encodeURIComponent(vMatch[1])}` : '';
log('version (from index.html) =', vMatch ? vMatch[1] : '(none)');

const esc = (s) => String(s == null ? '' : s)
    .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

const page = (id, data) => {
    const pi = data.personal_info || {};
    const title = `${pi.name} — ${pi.headline} (CV)`;
    return `<!DOCTYPE html>
<html lang="en">
<!-- GENERATED by tools/build-cv-pages.js from cv_profiles["${id}"] in data/resume.json — do not edit by hand -->
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <meta name="robots" content="noindex, nofollow">
    <base href="../../">
    <title>${esc(title)}</title>
    <link rel="icon" type="image/svg+xml" href="assets/favicon.svg">
    <link rel="stylesheet" href="assets/css/main.css${v}">
    <style>
        .cv-variant { max-width: 560px; margin: 15vh auto; padding: 0 16px; text-align: center; }
        .cv-variant h1 { margin-bottom: .25rem; }
        .cv-variant p { color: #5F6B7A; }
        .cv-variant button { margin-top: 1.5rem; padding: .75rem 1.5rem; font-size: 1rem; cursor: pointer;
            border: 0; border-radius: 6px; background: #1F3A5F; color: #fff; }
        .cv-variant button[disabled] { opacity: .6; cursor: default; }
    </style>
</head>
<body>
<main class="cv-variant">
    <h1>${esc(pi.name)}</h1>
    <p>${esc(pi.headline)}</p>
    <button type="button" id="cv-download">Download CV (PDF)</button>
    <p id="cv-status" role="status"></p>
</main>
<script src="atoms/resume-data-loader/impl.js${v}"></script>
<script src="atoms/pdf-generator/impl.js${v}"></script>
<script>
    (function () {
        var PROFILE = ${JSON.stringify(id)};
        var btn = document.getElementById('cv-download');
        var status = document.getElementById('cv-status');
        var generator = new PDFGenerator(new ResumeDataLoader());
        var run = function () {
            btn.disabled = true;
            status.textContent = 'Generating PDF…';
            generator.generateAndDownload(null, {profile: PROFILE}).then(function (r) {
                console.debug('[cv-page]', PROFILE, r);
                status.textContent = r.success ? 'Downloaded.' : 'Failed: ' + r.error;
                btn.disabled = false;
            });
        };
        btn.addEventListener('click', run);
        run(); // download right away; the button repeats it
    })();
</script>
</body>
</html>
`;
};

const ids = Object.keys(raw.cv_profiles || {}).filter(id => id !== ResumeDataLoader.DEFAULT_PROFILE);

const hubPage = () => {
    const site = String((raw.site_config || {}).url || '').replace(/\/+$/, '');
    const hash = (raw.site_config || {}).cv_hub_passcode_sha256 || '';
    const roles = [ResumeDataLoader.DEFAULT_PROFILE, ...ids].map(id => {
        const isDefault = id === ResumeDataLoader.DEFAULT_PROFILE;
        const headline = loader.filterRenderable(loader.applyProfile(raw, id)).personal_info.headline;
        return {id, title: isDefault ? `General: ${headline}` : headline, link: isDefault ? '' : `${site}/cv/${id}/`};
    });
    const json = (v) => JSON.stringify(v).replace(/</g, '\\u003c');
    return `<!DOCTYPE html>
<html lang="en">
<!-- GENERATED by tools/build-cv-pages.js from cv_profiles in data/resume.json — do not edit by hand -->
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <meta name="robots" content="noindex, nofollow">
    <base href="../">
    <title>CV</title>
    <link rel="icon" type="image/svg+xml" href="assets/favicon.svg">
    <link rel="stylesheet" href="assets/css/main.css${v}">
    <style>
        .cv-hub { max-width: 640px; margin: 10vh auto; padding: 0 16px; }
        .cv-hub form { display: flex; gap: .5rem; flex-wrap: wrap; }
        .cv-hub input { flex: 1 1 200px; padding: .6rem .75rem; font-size: 1rem; border: 1px solid #c9ced6; border-radius: 6px; }
        .cv-hub button { padding: .6rem 1rem; font-size: .95rem; cursor: pointer; border: 1px solid #1F3A5F; border-radius: 6px; background: #1F3A5F; color: #fff; }
        .cv-hub button.cv-hub__secondary { background: #fff; color: #1F3A5F; }
        .cv-hub button[disabled] { opacity: .6; cursor: default; }
        .cv-hub__role { display: flex; align-items: center; justify-content: space-between; gap: .75rem; flex-wrap: wrap; padding: .9rem 0; border-bottom: 1px solid #e0e0e0; }
        .cv-hub__actions { display: flex; gap: .5rem; }
        .cv-hub__status { color: #5F6B7A; min-height: 1.5rem; margin-top: .75rem; }
    </style>
</head>
<body>
<main class="cv-hub">
    <h1>CV</h1>
    <form id="cv-gate">
        <input id="cv-passcode" type="password" autocomplete="current-password" aria-label="Passcode" placeholder="Passcode" required>
        <button type="submit">Open</button>
    </form>
    <div id="cv-roles" hidden></div>
    <p id="cv-status" class="cv-hub__status" role="status"></p>
</main>
<script src="atoms/resume-data-loader/impl.js${v}"></script>
<script src="atoms/pdf-generator/impl.js${v}"></script>
<script>
    (function () {
        // Made it to this line? Nice work, you are clearly my kind of person.
        // This is a polite curtain, not a lock, so there is no need to crack it: just ask me for the passcode.
        var HASH = ${json(hash)};
        var SALT = ${json(SALT)};
        var ROLES = ${json(roles)};
        var KEY = 'cv-hub-unlocked';
        var gate = document.getElementById('cv-gate');
        var list = document.getElementById('cv-roles');
        var status = document.getElementById('cv-status');
        var generator = new PDFGenerator(new ResumeDataLoader());

        var sha256 = function (text) {
            return crypto.subtle.digest('SHA-256', new TextEncoder().encode(text)).then(function (buf) {
                return Array.from(new Uint8Array(buf)).map(function (b) { return b.toString(16).padStart(2, '0'); }).join('');
            });
        };
        var button = function (label, secondary, onClick) {
            var b = document.createElement('button');
            b.type = 'button';
            b.textContent = label;
            if (secondary) b.className = 'cv-hub__secondary';
            b.addEventListener('click', function () { onClick(b); });
            return b;
        };
        var download = function (role, b) {
            b.disabled = true;
            status.textContent = 'Generating PDF: ' + role.title;
            generator.generateAndDownload(null, {profile: role.id}).then(function (r) {
                console.debug('[cv-hub]', role.id, r);
                status.textContent = r.success ? 'Downloaded: ' + role.title : 'Failed: ' + r.error;
                b.disabled = false;
            });
        };
        var copy = function (role) {
            var done = function () { status.textContent = 'Link copied: ' + role.link; };
            if (navigator.clipboard) {
                navigator.clipboard.writeText(role.link).then(done, function () { status.textContent = role.link; });
            } else {
                status.textContent = role.link;
            }
        };
        var unlock = function () {
            gate.hidden = true;
            list.hidden = false;
            ROLES.forEach(function (role) {
                var row = document.createElement('div');
                row.className = 'cv-hub__role';
                var name = document.createElement('span');
                name.textContent = role.title;
                var actions = document.createElement('div');
                actions.className = 'cv-hub__actions';
                actions.appendChild(button('Download PDF', false, function (b) { download(role, b); }));
                if (role.link) actions.appendChild(button('Copy link', true, function () { copy(role); }));
                row.appendChild(name);
                row.appendChild(actions);
                list.appendChild(row);
            });
        };

        var unlocked = false;
        try { unlocked = !!HASH && sessionStorage.getItem(KEY) === HASH; } catch (e) {}
        console.debug('[cv-hub] passcode set =', !!HASH, 'unlocked =', unlocked);
        if (!HASH) {
            gate.hidden = true;
            status.textContent = 'Passcode is not set yet.';
        } else if (unlocked) {
            unlock();
        }
        gate.addEventListener('submit', function (e) {
            e.preventDefault();
            sha256(SALT + document.getElementById('cv-passcode').value.trim()).then(function (h) {
                if (h !== HASH) {
                    status.textContent = 'Wrong passcode.';
                    return;
                }
                status.textContent = '';
                try { sessionStorage.setItem(KEY, HASH); } catch (err) {}
                unlock();
            });
        });
    })();
</script>
</body>
</html>
`;
};
for (const id of ids) {
    if (!/^[a-z0-9-]+$/.test(id)) throw new Error(`cv_profiles key "${id}": use lowercase letters, digits and dashes`);
    const data = loader.filterRenderable(loader.applyProfile(raw, id));
    fs.mkdirSync(rel('cv', id), {recursive: true});
    fs.writeFileSync(rel('cv', id, 'index.html'), page(id, data));
    log('wrote', `cv/${id}/index.html`, '→', data.personal_info.headline);
}

// remove pages of profiles that no longer exist
if (fs.existsSync(rel('cv'))) {
    for (const dir of fs.readdirSync(rel('cv'))) {
        if (!ids.includes(dir) && fs.existsSync(rel('cv', dir, 'index.html'))) {
            fs.rmSync(rel('cv', dir), {recursive: true});
            log('removed', `cv/${dir}/`);
        }
    }
}
fs.writeFileSync(rel('cv', 'index.html'), hubPage());
log('wrote cv/index.html, passcode set =', !!(raw.site_config || {}).cv_hub_passcode_sha256);
log('done:', ids.length, 'page(s)');
