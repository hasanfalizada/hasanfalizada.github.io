#!/usr/bin/env node
// +++===+++ 2026-11-05 Asia/Baku — Hasan Alizada — CV variant pages builder (no npm, no external services).
//
// For every key of cv_profiles in data/resume.json (except "default", which is the site's "Resume" button) this script
// generates cv/<profile>/index.html — an unlisted page that downloads the CV variant as PDF:
//     https://hasanfalizada.github.io/cv/solution-architect/
// The pages hold NO resume content: PDFGenerator renders it in the browser from data/resume.json (single source of truth).
// Pages are noindex and are not added to sitemap.xml. Unlisted is not private: resume.json itself is public.
// Pages of profiles removed from resume.json are deleted. Version (?v=) is read from index.html.
//
// Usage (from the repository root, after changing cv_profiles):
//     node tools/build-cv-pages.js

'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const rel = (...p) => path.join(ROOT, ...p);
const log = (...a) => console.log('[build-cv-pages]', ...a);

const ResumeDataLoader = require(rel('atoms/resume-data-loader/impl.js'));
console.debug = () => {}; // silence atoms' debug logging in CLI output

const raw = JSON.parse(fs.readFileSync(rel('data/resume.json'), 'utf8'));
const loader = new ResumeDataLoader();
const validation = loader.validateResumeStructure(raw);
if (!validation.valid) throw new Error('resume.json is invalid: ' + validation.errors.join('; '));

const indexHtml = fs.readFileSync(rel('index.html'), 'utf8');
const vMatch = indexHtml.match(/assets\/js\/main\.js\?v=([^"']+)/);
const v = vMatch ? `?v=${encodeURIComponent(vMatch[1])}` : '';
log('version (from index.html) =', vMatch ? vMatch[1] : '(none)');

const esc = (s) => String(s == null ? '' : s)
    .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

const page = (id, data) => {
    const pi = data.personal_info || {};
    const title = `${pi.name} — ${pi.headline} (CV)`;
    return `<!DOCTYPE html>
<html lang="en">
<!-- GENERATED by tools/build-cv-pages.js from cv_profiles["${id}"] in data/resume.json — do not edit by hand -->
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <meta name="robots" content="noindex, nofollow">
    <base href="../../">
    <title>${esc(title)}</title>
    <link rel="icon" type="image/svg+xml" href="assets/favicon.svg">
    <link rel="stylesheet" href="assets/css/main.css${v}">
    <style>
        .cv-variant { max-width: 560px; margin: 15vh auto; padding: 0 16px; text-align: center; }
        .cv-variant h1 { margin-bottom: .25rem; }
        .cv-variant p { color: #5F6B7A; }
        .cv-variant button { margin-top: 1.5rem; padding: .75rem 1.5rem; font-size: 1rem; cursor: pointer;
            border: 0; border-radius: 6px; background: #1F3A5F; color: #fff; }
        .cv-variant button[disabled] { opacity: .6; cursor: default; }
    </style>
</head>
<body>
<main class="cv-variant">
    <h1>${esc(pi.name)}</h1>
    <p>${esc(pi.headline)}</p>
    <button type="button" id="cv-download">Download CV (PDF)</button>
    <p id="cv-status" role="status"></p>
</main>
<script src="atoms/resume-data-loader/impl.js${v}"></script>
<script src="atoms/pdf-generator/impl.js${v}"></script>
<script>
    (function () {
        var PROFILE = ${JSON.stringify(id)};
        var btn = document.getElementById('cv-download');
        var status = document.getElementById('cv-status');
        var generator = new PDFGenerator(new ResumeDataLoader());
        var run = function () {
            btn.disabled = true;
            status.textContent = 'Generating PDF…';
            generator.generateAndDownload(null, {profile: PROFILE}).then(function (r) {
                console.debug('[cv-page]', PROFILE, r);
                status.textContent = r.success ? 'Downloaded.' : 'Failed: ' + r.error;
                btn.disabled = false;
            });
        };
        btn.addEventListener('click', run);
        run(); // download right away; the button repeats it
    })();
</script>
</body>
</html>
`;
};

const ids = Object.keys(raw.cv_profiles || {}).filter(id => id !== ResumeDataLoader.DEFAULT_PROFILE);
for (const id of ids) {
    if (!/^[a-z0-9-]+$/.test(id)) throw new Error(`cv_profiles key "${id}": use lowercase letters, digits and dashes`);
    const data = loader.filterRenderable(loader.applyProfile(raw, id));
    fs.mkdirSync(rel('cv', id), {recursive: true});
    fs.writeFileSync(rel('cv', id, 'index.html'), page(id, data));
    log('wrote', `cv/${id}/index.html`, '→', data.personal_info.headline);
}

// remove pages of profiles that no longer exist
if (fs.existsSync(rel('cv'))) {
    for (const dir of fs.readdirSync(rel('cv'))) {
        if (!ids.includes(dir) && fs.existsSync(rel('cv', dir, 'index.html'))) {
            fs.rmSync(rel('cv', dir), {recursive: true});
            log('removed', `cv/${dir}/`);
        }
    }
}
log('done:', ids.length, 'page(s)');
