#!/usr/bin/env node
// +++===+++ 2026-11-09 Asia/Baku — Hasan Alizada — Static site pages builder (no npm, no external services).
// Generates work/, services/ and privacy/ index.html from site_pages in data/resume.json.
// A page that is switched off is deleted, but only if this script generated it. Version (?v=) is read from index.html.
//
// Usage (from the repository root, after changing data/resume.json):
//     node tools/build-pages.js        (or node tools/build.js to rebuild everything)

'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const rel = (...p) => path.join(ROOT, ...p);
const log = (...a) => console.log('[build-pages]', ...a);

const ResumeDataLoader = require(rel('atoms/resume-data-loader/impl.js'));
const {renderPages, isEnabled, ALL_PAGE_IDS} = require('./lib/site-pages.js');
console.debug = () => {}; // silence atoms' debug logging in CLI output

const raw = JSON.parse(fs.readFileSync(rel('data/resume.json'), 'utf8'));
const loader = new ResumeDataLoader();
const validation = loader.validateResumeStructure(raw);
if (!validation.valid) throw new Error('resume.json is invalid: ' + validation.errors.join('; '));
const data = loader.filterRenderable(loader.applyProfile(raw));

const vMatch = fs.readFileSync(rel('index.html'), 'utf8').match(/assets\/js\/main\.js\?v=([^"']+)/);
const version = vMatch ? vMatch[1] : '';
log('enabled =', JSON.stringify(isEnabled(data)), '| version =', version || '(none)');

const pages = renderPages(data, version);
for (const page of pages) {
    fs.mkdirSync(path.dirname(rel(page.path)), {recursive: true});
    fs.writeFileSync(rel(page.path), page.html, 'utf8');
    log('wrote', page.path);
}

const written = new Set(pages.map(p => p.path));
for (const id of ALL_PAGE_IDS) {
    const file = `${id}/index.html`;
    if (written.has(file) || !fs.existsSync(rel(file))) continue;
    if (!/GENERATED by tools\/build-pages\.js/.test(fs.readFileSync(rel(file), 'utf8'))) continue;
    fs.rmSync(rel(id), {recursive: true});
    log('removed', `${id}/`, '(switched off)');
}
log('done');
